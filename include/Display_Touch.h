class Button
{
private:
    int x, y, w, h;
    const char *label;
    uint16_t colorBg, colorText, colorBorder;
    bool isPressed = false;
    void (*clickListener)() = nullptr;

public:
    Button() : x(0), y(0), w(0), h(0), label("") {}

    Button(int x, int y, int w, int h, const char *label,
           uint16_t colorBg = CLR_HEADER,
           uint16_t colorText = CLR_HEADER_TEXT,
           uint16_t colorBorder = CLR_HEADER)
    {
        this->x = x;
        this->y = y;
        this->w = w;
        this->h = h;
        this->label = label;
        this->colorBg = colorBg;
        this->colorText = colorText;
        this->colorBorder = colorBorder;
    }

    void setOnClickListener(void (*listener)())
    {
        clickListener = listener;
    }

    // Geometry accessors — used to repaint a button's background to reflect toggle state.
    int getX() const { return x; }
    int getY() const { return y; }
    int getW() const { return w; }
    int getH() const { return h; }

    void draw(bool pressed = false)
    {
        uint16_t bg = pressed ? colorBorder : colorBg;
        uint16_t txt = pressed ? colorBg : colorText;
        tft.fillRoundRect(x, y, w, h, 5, bg);
        tft.drawRoundRect(x, y, w, h, 5, colorBorder);
        tft.setTextColor(txt);
        tft.setTextSize(1);
        int16_t tx = x + (w - strlen(label) * 6) / 2;
        int16_t ty = y + (h - 8) / 2;
        tft.setCursor(tx, ty);
        tft.print(label);
    }

    bool contains(int tx, int ty)
    {
        return tx >= x && tx <= x + w && ty >= y && ty <= y + h;
    }

    void handleTouch(int tx, int ty, bool touching)
    {
        if (touching && contains(tx, ty))
        {
            if (!isPressed)
            {
                isPressed = true;
                // draw(true);
            }
        }
        else if (isPressed)
        {
            isPressed = false;
            // draw(false);
            beep();
            if (!touching && clickListener)
                clickListener();
        }
    }

    void hide()
    {
        tft.fillRect(x, y, w, h, CLR_BG);
    }
};

